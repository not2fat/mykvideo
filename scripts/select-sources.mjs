// Build-time default-source selector for the three VOD deployments.
//
// Usage: VOD_PROFILE=clean|full|dirty node scripts/select-sources.mjs
// Reads lib/api/source-profiles/<profile>.json and writes
// lib/api/default-sources.generated.ts, which lib/api/default-sources.ts
// re-exports. Runs automatically before every build via the `prebuild`
// script and via `pages:build`, so each Cloudflare Pages project only ever
// bundles its own profile's sources (a runtime filter would leak the other
// profiles' source URLs into the client JS bundle).
//
// Default profile is `clean` when VOD_PROFILE is unset or invalid.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROFILES = ['clean', 'full', 'dirty'];

const requested = (process.env.VOD_PROFILE || 'clean').trim().toLowerCase();
const profile = PROFILES.includes(requested) ? requested : 'clean';

const sources = JSON.parse(
  readFileSync(join(root, 'lib', 'api', 'source-profiles', `${profile}.json`), 'utf8')
);

const out =
  `// AUTO-GENERATED by scripts/select-sources.mjs (VOD_PROFILE=${profile}).\n` +
  `// Do not edit by hand; edit lib/api/source-profiles/${profile}.json instead.\n` +
  `import type { VideoSource } from '@/lib/types';\n\n` +
  `export const DEFAULT_SOURCES: VideoSource[] = ${JSON.stringify(sources, null, 2)};\n`;

writeFileSync(join(root, 'lib', 'api', 'default-sources.generated.ts'), out);
console.log(`[select-sources] VOD_PROFILE=${profile}, ${sources.length} sources written`);
