// Build-time profile selector for the three VOD deployments.
//
// Usage: VOD_PROFILE=clean|full|dirty node scripts/select-profile.mjs
// Reads lib/api/source-profiles/<profile>.json and
// lib/config/site-profiles.json, then writes:
//   - lib/api/default-sources.generated.ts (re-exported by default-sources.ts)
//   - lib/config/site-brand.generated.ts (consumed by site-config.ts)
// Runs automatically before every build via the `prebuild` script and via
// `pages:build`, so each Cloudflare Pages project only ever bundles its own
// profile's sources and branding. A runtime filter would leak the other
// profiles' source URLs into the client JS bundle, so selection must happen
// here, at build time.
//
// Default profile is `clean` when VOD_PROFILE is unset or invalid.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROFILES = ['clean', 'full', 'dirty'];

const requested = (process.env.VOD_PROFILE || 'clean').trim().toLowerCase();
const profile = PROFILES.includes(requested) ? requested : 'clean';

const sources = JSON.parse(
  readFileSync(join(root, 'lib', 'api', 'source-profiles', `${profile}.json`), 'utf8')
);

const sourcesOut =
  `// AUTO-GENERATED by scripts/select-profile.mjs (VOD_PROFILE=${profile}).\n` +
  `// Do not edit by hand; edit lib/api/source-profiles/${profile}.json instead.\n` +
  `import type { VideoSource } from '@/lib/types';\n\n` +
  `export const DEFAULT_SOURCES: VideoSource[] = ${JSON.stringify(sources, null, 2)};\n`;

writeFileSync(join(root, 'lib', 'api', 'default-sources.generated.ts'), sourcesOut);
console.log(`[select-profile] VOD_PROFILE=${profile}, ${sources.length} sources written`);

const brands = JSON.parse(
  readFileSync(join(root, 'lib', 'config', 'site-profiles.json'), 'utf8')
);
const brand = brands[profile];

const brandOut =
  `// AUTO-GENERATED by scripts/select-profile.mjs (VOD_PROFILE=${profile}).\n` +
  `// Do not edit by hand; edit lib/config/site-profiles.json instead.\n` +
  `export const SITE_BRAND = ${JSON.stringify(brand, null, 2)};\n`;

writeFileSync(join(root, 'lib', 'config', 'site-brand.generated.ts'), brandOut);
console.log(`[select-profile] brand: ${brand.name} (${brand.icon})`);
